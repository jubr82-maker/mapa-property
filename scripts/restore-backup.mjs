// Restauration d'une sauvegarde nocturne chiffree (oct. 2026).
//
// Dechiffre (AES-256-GCM, BACKUP_ENCRYPTION_KEY), decompresse et produit le
// SQL de restauration (tables, lignes, contraintes, index, regles d'acces,
// sequences), puis l'execute avec psql dans la base DESIGNEE, qui doit etre
// vide. Jamais dans la base de production sans une confirmation tapee.
// Mode d'emploi pas a pas : docs/sauvegarde.md.
//
// Usage (depuis la racine du depot, Terminal.app) :
//   node --import tsx scripts/restore-backup.mjs --latest --sql-out restauration.sql
//   node --import tsx scripts/restore-backup.mjs --file sauvegarde.json.gz.enc --target "postgresql://..."
//   node --import tsx scripts/restore-backup.mjs --key backups/nightly/2026-10-08T01-00-04Z.json.gz.enc --target "postgresql://..."
// Options : --file <chemin local> | --key <objet R2> | --latest ;
//           --sql-out <fichier> (ecrit le SQL sans toucher a aucune base) ;
//           --target <adresse postgresql> (execute le SQL avec psql).
// psql : /opt/homebrew/opt/libpq/bin/psql par defaut (brew install libpq),
// ou PSQL_BIN=/chemin/psql.

import { execFile } from "node:child_process";
import { promisify } from "node:util";
import { readFile, writeFile, mkdtemp, rm, access } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { gunzipSync } from "node:zlib";
import { createInterface } from "node:readline/promises";
import { config } from "dotenv";

const __dirname = dirname(fileURLToPath(import.meta.url));
config({ path: join(__dirname, "..", ".env.local") });

const execFileP = promisify(execFile);
const PRODUCTION_REF = "dutfkblygfvhhwpzxmfz";
const PROD_CONFIRMATION = `RESTAURER EN PRODUCTION ${PRODUCTION_REF}`;
const NON_EMPTY_CONFIRMATION = "RESTAURER DANS UNE BASE NON VIDE";
const DEFAULT_PSQL = "/opt/homebrew/opt/libpq/bin/psql";

const { decryptBackup, parseBackupKey } = await import("../lib/backup/crypto.ts");

function arg(name) {
  const i = process.argv.indexOf(`--${name}`);
  return i > 0 ? process.argv[i + 1] : undefined;
}
const flag = (name) => process.argv.includes(`--${name}`);
const log = (m) => console.log(`[restauration] ${m}`);
const mask = (url) => url.replace(/(:\/\/[^:]+:)[^@]+(@)/, "$1***$2");
const ident = (s) => `"${String(s).replace(/"/g, '""')}"`;
const lit = (s) => (s === null || s === undefined ? "NULL" : `'${String(s).replace(/'/g, "''")}'`);

async function loadEncrypted() {
  const file = arg("file");
  if (file) return readFile(file);
  const { getBackupFromR2, listBackupR2Objects, isBackupR2Configured } = await import("../lib/r2.ts");
  if (!isBackupR2Configured()) throw new Error("R2 non configure (.env.local : R2_ACCOUNT_ID, R2_BACKUP_*).");
  let key = arg("key");
  if (!key && flag("latest")) {
    const objects = await listBackupR2Objects("backups/nightly/");
    key = objects.map((o) => o.key).filter((k) => k.endsWith(".json.gz.enc")).sort().pop();
    if (!key) throw new Error("aucune sauvegarde nocturne dans R2.");
  }
  if (!key) throw new Error("indiquer --file, --key ou --latest.");
  log(`lecture de ${key}`);
  return getBackupFromR2(key);
}

function dollarTag(json) {
  let tag = "mapa_json";
  while (json.includes(`$${tag}$`)) tag += "_x";
  return `$${tag}$`;
}

/** SQL complet de restauration a partir du contenu dechiffre. */
export function restoreSql(payload) {
  if (payload?.format !== "mapa-backup-v1") throw new Error("format de sauvegarde inconnu.");
  const out = ["-- Restauration MAPA Property", `-- sauvegarde du ${payload.created_at}`, "\\set ON_ERROR_STOP on", "BEGIN;"];
  for (const s of payload.catalog.sequences ?? []) out.push(`CREATE SEQUENCE IF NOT EXISTS public.${ident(s.name)};`);
  for (const t of payload.catalog.tables) {
    const cols = t.columns.map((c) => {
      const parts = [ident(c.name), c.type];
      if (c.identity === "a") parts.push("GENERATED ALWAYS AS IDENTITY");
      else if (c.identity === "d") parts.push("GENERATED BY DEFAULT AS IDENTITY");
      else if (c.default) parts.push(`DEFAULT ${c.default}`);
      if (c.not_null) parts.push("NOT NULL");
      return `  ${parts.join(" ")}`;
    });
    out.push(`CREATE TABLE public.${ident(t.name)} (\n${cols.join(",\n")}\n);`);
  }
  // Lignes, par paquets de 500.
  for (const t of payload.catalog.tables) {
    const rows = payload.data[t.name] ?? [];
    const overriding = t.columns.some((c) => c.identity === "a") ? " OVERRIDING SYSTEM VALUE" : "";
    for (let i = 0; i < rows.length; i += 500) {
      const json = JSON.stringify(rows.slice(i, i + 500));
      const tag = dollarTag(json);
      out.push(`INSERT INTO public.${ident(t.name)}${overriding} SELECT * FROM jsonb_populate_recordset(NULL::public.${ident(t.name)}, ${tag}${json}${tag}::jsonb);`);
    }
  }
  // Contraintes : cles primaires, puis uniques et verifications, puis cles etrangeres.
  const order = { p: 0, u: 1, c: 2, x: 3, f: 4 };
  const all = payload.catalog.tables.flatMap((t) => (t.constraints ?? []).map((c) => ({ t: t.name, ...c })));
  all.sort((a, b) => (order[a.type] ?? 9) - (order[b.type] ?? 9));
  for (const c of all) if (c.type !== "n") out.push(`ALTER TABLE public.${ident(c.t)} ADD CONSTRAINT ${ident(c.name)} ${c.def};`);
  for (const t of payload.catalog.tables) for (const ix of t.indexes ?? []) out.push(`${ix};`);
  for (const s of payload.catalog.sequences ?? []) if (s.last_value !== null && s.last_value !== undefined) out.push(`SELECT setval('public.${ident(s.name).replace(/'/g, "''")}', ${Number(s.last_value)});`);
  for (const t of payload.catalog.tables) if (t.rls) out.push(`ALTER TABLE public.${ident(t.name)} ENABLE ROW LEVEL SECURITY;`);
  out.push("COMMIT;");
  // Regles d'acces : elles appellent des fonctions (is_mapa_admin...) a
  // recreer depuis supabase/ ; une regle impossible est signalee, pas bloquante.
  for (const t of payload.catalog.tables) {
    for (const p of t.policies ?? []) {
      const roles = (p.roles ?? []).map((r) => (r === "public" ? "public" : ident(r))).join(", ") || "public";
      const sql = `CREATE POLICY ${ident(p.name)} ON public.${ident(t.name)} AS ${p.permissive} FOR ${p.cmd} TO ${roles}${p.using ? ` USING (${p.using})` : ""}${p.check ? ` WITH CHECK (${p.check})` : ""}`;
      out.push(`DO $policy$ BEGIN EXECUTE ${lit(sql)}; EXCEPTION WHEN OTHERS THEN RAISE WARNING 'regle % non recreee : %', ${lit(p.name)}, SQLERRM; END $policy$;`);
    }
  }
  return out.join("\n") + "\n";
}

async function psqlBin() {
  const bin = process.env.PSQL_BIN?.trim() || DEFAULT_PSQL;
  await access(bin).catch(() => {
    throw new Error(`psql introuvable a ${bin} (brew install libpq, ou PSQL_BIN=/chemin/psql).`);
  });
  return bin;
}

async function confirm(expected, question) {
  const rl = createInterface({ input: process.stdin, output: process.stdout });
  const answer = await rl.question(`${question}\nTapez exactement : ${expected}\n> `);
  rl.close();
  if (answer.trim() !== expected) throw new Error("confirmation incorrecte, restauration annulee.");
}

async function main() {
  const key = parseBackupKey(process.env.BACKUP_ENCRYPTION_KEY);
  const payload = JSON.parse(gunzipSync(decryptBackup(await loadEncrypted(), key)).toString("utf8"));
  const tables = payload.catalog.tables.length;
  const rows = Object.values(payload.data).reduce((n, r) => n + r.length, 0);
  log(`sauvegarde du ${payload.created_at} : ${tables} tables, ${rows} lignes`);
  const sql = restoreSql(payload);

  const sqlOut = arg("sql-out");
  if (sqlOut) {
    await writeFile(sqlOut, sql, { mode: 0o600 });
    log(`SQL ecrit dans ${sqlOut} (aucune base modifiee). Il contient des donnees personnelles : le supprimer apres usage.`);
  }
  const target = arg("target");
  if (!target) {
    if (!sqlOut) log("aucune cible : indiquer --target <adresse postgresql> ou --sql-out <fichier>.");
    return;
  }
  const bin = await psqlBin();
  if (target.includes(PRODUCTION_REF)) {
    await confirm(PROD_CONFIRMATION, "ATTENTION : la cible est la base de PRODUCTION.");
  }
  const { stdout } = await execFileP(bin, [target, "-tAc", "select count(*) from pg_tables where schemaname = 'public'"]);
  if (Number(stdout.trim()) > 0) {
    await confirm(NON_EMPTY_CONFIRMATION, `La base cible contient deja ${stdout.trim()} tables dans le schema public.`);
  }
  const dir = await mkdtemp(join(tmpdir(), "mapa-restauration-"));
  const file = join(dir, "restauration.sql");
  try {
    await writeFile(file, sql, { mode: 0o600 });
    log(`execution dans ${mask(target)}`);
    await execFileP(bin, [target, "-v", "ON_ERROR_STOP=1", "-q", "-f", file], { maxBuffer: 1024 * 1024 * 64 });
    log("restauration terminee.");
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  main().catch((e) => {
    console.error(`[restauration] ECHEC : ${e instanceof Error ? e.message : String(e)}`);
    process.exit(1);
  });
}
